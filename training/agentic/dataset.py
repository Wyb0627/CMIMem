"""AgenticRLDataset: Groups sessions into trajectories for multi-turn agentic RL.

Each sample represents one conversation (question_id) with multiple sessions.
The agent loop processes sessions sequentially as turns, building memory
incrementally and receiving per-turn CMI reward.

Data source: reuses existing longmemeval parquet files generated by
prepare_rl_data_online.py (no expert trajectories required).

The dataset does NOT tokenize prompts — real prompts are constructed
dynamically by MemoryBuilderAgentLoop at rollout time based on the
current memory state after each turn.
"""

from __future__ import annotations

import json
import logging
import os
from typing import Any, Dict, List, Optional, Sequence, Union

import numpy as np
import pyarrow.parquet as pq
import torch
from torch.utils.data import Dataset

logger = logging.getLogger(__name__)


class AgenticRLDataset(Dataset):
    """Multi-turn agentic RL dataset for MemBuilder.

    Reads per-session rows from parquet and groups them by conversation_id
    into multi-session trajectories. Each __getitem__ returns one trajectory
    (all sessions for one conversation + its QA questions).

    Compatible with verl's custom_cls dataset loading:
        data:
          custom_cls:
            path: training/agentic/dataset.py
            name: AgenticRLDataset
    """

    def __init__(
        self,
        data_files: Union[str, Sequence[str]],
        tokenizer: Any = None,
        processor: Any = None,
        config: Any = None,
    ) -> None:
        if isinstance(data_files, str):
            data_files = [data_files]
        else:
            data_files = list(data_files)

        self.tokenizer = tokenizer
        self.processor = processor
        self.config = config

        # Read config options
        max_sessions = 64
        warmup_random_sessions = 0
        if config is not None:
            try:
                custom_cls = config.get("custom_cls", {}) if hasattr(config, "get") else {}
                if hasattr(custom_cls, "get"):
                    max_sessions = int(custom_cls.get("max_sessions", 64) or 64)
                    warmup_random_sessions = int(
                        custom_cls.get("warmup_random_sessions", 0) or 0
                    )
            except Exception:
                pass
        self.max_sessions = max_sessions
        self.warmup_random_sessions = warmup_random_sessions

        # verl-compatible tokenization config
        self.max_prompt_length = 1024
        self._chat_template_kwargs = {}
        if config is not None:
            try:
                self.max_prompt_length = int(
                    config.get("max_prompt_length", 1024) or 1024
                )
            except Exception:
                pass
            try:
                act_kwargs = config.get("apply_chat_template_kwargs", {})
                self._chat_template_kwargs = dict(act_kwargs) if act_kwargs else {}
            except Exception:
                pass

        # Load and group records by conversation_id
        raw_records: List[dict] = []
        for path in data_files:
            if path.endswith(".jsonl"):
                import json as _json
                with open(path, "r", encoding="utf-8") as f:
                    for line in f:
                        line = line.strip()
                        if line:
                            raw_records.append(_json.loads(line))
            else:
                table = pq.read_table(path)
                # Compatible with pyarrow < 8.0 (no to_pylist())
                if hasattr(table, "to_pylist"):
                    raw_records.extend(table.to_pylist())
                else:
                    raw_records.extend(table.to_pandas().to_dict("records"))

        # Group sessions by conversation_id, preserving session_index order
        from collections import defaultdict
        grouped: Dict[str, List[dict]] = defaultdict(list)
        for rec in raw_records:
            conv_id = str(rec.get("conversation_id", rec.get("conv_id", "unknown")))

            # Parse extra_info if stored as JSON string (parquet format)
            extra_info = rec.get("extra_info", {})
            if isinstance(extra_info, str):
                try:
                    extra_info = json.loads(extra_info)
                    rec["extra_info"] = extra_info
                except (json.JSONDecodeError, TypeError):
                    extra_info = {}

            if extra_info and isinstance(extra_info, dict):
                # extra_info wrapped format (from prepare_rl_data_online.py parquet)
                session_index = extra_info.get("session_index", rec.get("session_index", 0))
            else:
                session_index = rec.get("session_index", 0)

            grouped[conv_id].append((int(session_index), rec))

        # Sort sessions within each conversation and build trajectories
        self._trajectories: List[dict] = []
        for conv_id, session_pairs in grouped.items():
            session_pairs.sort(key=lambda x: x[0])
            sessions_ordered = [rec for _, rec in session_pairs]

            # Extract questions from the first session that has them
            questions = []
            for rec in sessions_ordered:
                ei = rec.get("extra_info", {})
                qs = ei.get("questions", rec.get("questions", []))
                if qs:
                    questions = list(qs)
                    break

            # Truncate if too many sessions
            if len(sessions_ordered) > self.max_sessions:
                sessions_ordered = sessions_ordered[: self.max_sessions]

            self._trajectories.append({
                "conversation_id": conv_id,
                "sessions": sessions_ordered,
                "questions": questions,
            })

        logger.info(
            f"AgenticRLDataset loaded: {len(self._trajectories)} trajectories "
            f"from {len(raw_records)} session records"
        )

    def __len__(self) -> int:
        return len(self._trajectories)

    def __getitem__(self, idx: int) -> dict:
        traj = self._trajectories[idx]
        conv_id = traj["conversation_id"]
        sessions_raw = traj["sessions"]
        questions = traj["questions"]

        # Cold-start warmup: prepend random sessions from other trajectories.
        # These are unrelated sessions that force the model to build some
        # initial memory before encountering the actual trajectory.
        # Controlled by warmup_random_sessions hyperparameter (default 0 = off).
        warmup_sessions: List[dict] = []
        if self.warmup_random_sessions > 0 and len(self._trajectories) > 1:
            rng = np.random.default_rng()
            other_indices = [i for i in range(len(self._trajectories)) if i != idx]
            chosen_traj_idx = rng.choice(other_indices)
            donor_sessions = self._trajectories[chosen_traj_idx]["sessions"]
            n_warmup = min(self.warmup_random_sessions, len(donor_sessions))
            warmup_sessions = list(donor_sessions[:n_warmup])

        # Extract session messages, timestamps, and state_before for each session
        session_messages_list: List[List[Dict[str, str]]] = []
        session_timestamps: List[str] = []
        state_before_list: List[Dict[str, Any]] = []

        for rec in warmup_sessions + sessions_raw:
            extra_info = rec.get("extra_info", {})

            # Session messages
            session_data = extra_info.get("session", rec.get("session", {}))
            if isinstance(session_data, str):
                try:
                    session_data = json.loads(session_data)
                except (json.JSONDecodeError, TypeError):
                    session_data = {}
            messages = session_data.get("messages", [])
            if isinstance(messages, str):
                messages = [{"role": "user", "content": messages}]
            session_messages_list.append(messages)

            # Timestamp
            timestamp = session_data.get("timestamp", "")
            session_timestamps.append(str(timestamp) if timestamp else "")

            # State before (memory snapshot before this session)
            state_before = extra_info.get("state_before", rec.get("state_before", {}))
            if isinstance(state_before, str):
                try:
                    state_before = json.loads(state_before)
                except (json.JSONDecodeError, TypeError):
                    state_before = {}
            state_before_list.append(state_before)

        # Extract ground truth answers
        ground_truths = []
        for q in questions:
            if isinstance(q, dict):
                ground_truths.append(q.get("answer", ""))
            elif isinstance(q, str):
                ground_truths.append(q)

        # Placeholder prompt for verl collator (real prompt built by agent loop).
        # verl's _get_gen_batch asserts that input_ids / attention_mask /
        # position_ids exist as tensors in the batch, so we must tokenize a
        # short placeholder here. The agent loop will ignore these and build
        # the real prompt dynamically from memory state + session context.
        placeholder_prompt = [
            {"role": "system", "content": "You are a memory manager."},
            {"role": "user", "content": "Process the following sessions."},
        ]

        # Tokenize placeholder prompt
        raw_prompt = self.tokenizer.apply_chat_template(
            placeholder_prompt,
            add_generation_prompt=True,
            tokenize=False,
            **(self._chat_template_kwargs or {}),
        )
        model_inputs = self.tokenizer(
            raw_prompt, return_tensors="pt", add_special_tokens=False,
        )
        input_ids = model_inputs["input_ids"]
        attention_mask = model_inputs["attention_mask"]

        # Pad / truncate to max_prompt_length
        from verl.utils.torch_functional import postprocess_data
        input_ids, attention_mask = postprocess_data(
            input_ids=input_ids,
            attention_mask=attention_mask,
            max_length=self.max_prompt_length,
            pad_token_id=self.tokenizer.pad_token_id,
            left_pad=True,
            truncation="right",
        )

        from verl.utils.model import compute_position_id_with_mask
        position_ids = compute_position_id_with_mask(attention_mask)

        # Number of warmup sessions prepended (agent loop can use this to
        # skip warmup turns when computing final QA reward or logging)
        num_warmup = len(warmup_sessions)

        return {
            # Tensor keys required by verl's _get_gen_batch
            "input_ids": input_ids[0],
            "attention_mask": attention_mask[0],
            "position_ids": position_ids[0],
            # Non-tensor trajectory data (passed to agent loop via non_tensor_batch)
            "conversation_id": conv_id,
            "session_messages_list": session_messages_list,
            "session_timestamps": session_timestamps,
            "state_before_list": state_before_list,
            "questions": questions,
            "ground_truths": ground_truths,
            "num_warmup_sessions": num_warmup,
            "data_source": "memory_management_agentic",
        }


__all__ = ["AgenticRLDataset"]
